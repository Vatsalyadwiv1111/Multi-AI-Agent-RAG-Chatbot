import time
import logging
from dataclasses import dataclass
from typing import List, Optional
from evaluation.config import (
    FAITHFULNESS_THRESHOLD,
    ANSWER_RELEVANCE_THRESHOLD,
    CONTEXT_PRECISION_THRESHOLD,
    CONTEXT_RECALL_THRESHOLD,
    MAX_LATENCY_THRESHOLD_SECONDS
)
from evaluation.metrics import (
    compute_answer_relevance,
    compute_faithfulness_and_hallucination,
    compute_context_precision_and_recall
)

logger = logging.getLogger("LLMEvaluator")

@dataclass
class EvaluationResult:
    faithfulness: float
    answer_relevance: float
    context_precision: float
    context_recall: float
    hallucination_score: float
    retriever_performance: float
    latency_seconds: float
    passed_all_thresholds: bool
    summary: str

def evaluate_agent_response(
    query: str,
    response: str,
    context_docs: Optional[List[str]] = None,
    latency_seconds: float = 0.0
) -> EvaluationResult:
    """
    Evaluates every response generated by the multi-agent system.
    Measures:
    - Faithfulness
    - Answer Relevance
    - Context Precision
    - Context Recall
    - Hallucination Score
    - Retriever Performance
    - Latency
    """
    context_docs = context_docs or []

    relevance = compute_answer_relevance(query, response)
    faithfulness, hallucination = compute_faithfulness_and_hallucination(response, context_docs)
    precision, recall = compute_context_precision_and_recall(query, context_docs)
    retriever_perf = round(precision * recall, 2)

    passed = (
        faithfulness >= FAITHFULNESS_THRESHOLD and
        relevance >= ANSWER_RELEVANCE_THRESHOLD and
        precision >= CONTEXT_PRECISION_THRESHOLD and
        recall >= CONTEXT_RECALL_THRESHOLD and
        latency_seconds <= MAX_LATENCY_THRESHOLD_SECONDS
    )

    summary = (
        f"Relevance: {relevance:.2f} | Faithfulness: {faithfulness:.2f} | "
        f"Precision: {precision:.2f} | Recall: {recall:.2f} | "
        f"Hallucination: {hallucination:.2f} | Latency: {latency_seconds:.2f}s | "
        f"Passed: {passed}"
    )

    logger.info(f"[EVALUATION SUMMARY] {summary}")

    return EvaluationResult(
        faithfulness=faithfulness,
        answer_relevance=relevance,
        context_precision=precision,
        context_recall=recall,
        hallucination_score=hallucination,
        retriever_performance=retriever_perf,
        latency_seconds=round(latency_seconds, 2),
        passed_all_thresholds=passed,
        summary=summary
    )
